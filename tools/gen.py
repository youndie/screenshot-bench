#!/usr/bin/env python3
"""Generate N fixtures and the per-tool test sources that capture them.

    tools/gen.py 50

Every tool gets exactly one capture per fixture, at 360x640 px (density 1 / mdpi), wrapped in the
same BenchTheme. The only per-tool difference is what the tool's own documentation asks for.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ["ListScreen", "FormScreen", "CardGrid", "ProfileScreen", "SettingsScreen"]
W, H = 360, 640
CHUNK = 10  # fixtures per test class: Gradle forks distribute classes, not methods
HEADER = "// GENERATED by tools/gen.py — do not edit.\n"
TEST_DIRS = {
    "paparazzi": "paparazzi/src/test/kotlin/bench",
    "roborazzi-android": "roborazzi-android/src/test/kotlin/bench",
    "roborazzi-desktop": "roborazzi-desktop/src/test/kotlin/bench",
}


def write(rel, text):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(HEADER + text)


def chunks(ids):
    return [ids[i:i + CHUNK] for i in range(0, len(ids), CHUNK)]


def fixtures(ids):
    body = "package bench\n\nimport androidx.compose.runtime.Composable\n\n"
    body += f"const val FIXTURE_COUNT = {len(ids)}\n\n"
    for i, s in enumerate(ids):
        body += f"@Composable fun Fixture{s}() = {TEMPLATES[i % len(TEMPLATES)]}(seed = {i})\n"
    return body


def viddik(ids):
    # One annotated composable per fixture; KSP turns them into tests, sharded by the plugin.
    body = ("package bench\n\nimport androidx.compose.runtime.Composable\n"
            "import io.github.youndie.viddik.annotations.ViddikScreenshot\n"
            "import io.github.youndie.viddik.core.viddikTypography\n\n")
    for s in ids:
        body += (f'@ViddikScreenshot(name = "f{s}", group = "bench", width = {W}, height = {H})\n'
                 f"@Composable fun ViddikF{s}() = BenchTheme(viddikTypography()) {{ Fixture{s}() }}\n\n")
    return body


def paparazzi(c, part):
    body = ("package bench\n\nimport app.cash.paparazzi.DeviceConfig\nimport app.cash.paparazzi.Paparazzi\n"
            "import com.android.resources.Density\nimport org.junit.Rule\nimport org.junit.Test\n\n"
            f"class PaparazziTest{c:02d} {{\n"
            "    @get:Rule\n"
            "    val paparazzi = Paparazzi(\n"
            f"        deviceConfig = DeviceConfig(screenWidth = {W}, screenHeight = {H}, xdpi = 160, ydpi = 160, density = Density.MEDIUM),\n"
            '        theme = "android:Theme.Material.Light.NoActionBar",\n'
            "    )\n\n")
    for s in part:
        body += f"    @Test fun f{s}() = paparazzi.snapshot {{ BenchTheme {{ Fixture{s}() }} }}\n"
    return body + "}\n"


def roborazzi_android(c, part):
    # Robolectric with native graphics, a compose rule, one capture per test.
    body = ("package bench\n\nimport androidx.compose.ui.test.junit4.createComposeRule\n"
            "import androidx.compose.ui.test.onRoot\nimport com.github.takahirom.roborazzi.captureRoboImage\n"
            "import org.junit.Rule\nimport org.junit.Test\nimport org.junit.runner.RunWith\n"
            "import org.robolectric.RobolectricTestRunner\nimport org.robolectric.annotation.Config\n"
            "import org.robolectric.annotation.GraphicsMode\n\n"
            "@RunWith(RobolectricTestRunner::class)\n"
            "@GraphicsMode(GraphicsMode.Mode.NATIVE)\n"
            f'@Config(sdk = [36], qualifiers = "w{W}dp-h{H}dp-mdpi")\n'
            f"class RoborazziAndroidTest{c:02d} {{\n"
            "    @get:Rule\n    val compose = createComposeRule()\n\n")
    for s in part:
        body += (f"    @Test fun f{s}() {{\n"
                 f"        compose.setContent {{ BenchTheme {{ Fixture{s}() }} }}\n"
                 f'        compose.onRoot().captureRoboImage("build/goldens/f{s}.png")\n'
                 "    }\n")
    return body + "}\n"


def roborazzi_desktop(c, part):
    # Compose Desktop: the same Skiko renderer viddik uses.
    body = ("package bench\n\nimport androidx.compose.ui.test.ExperimentalTestApi\n"
            "import androidx.compose.ui.test.onRoot\nimport androidx.compose.ui.test.runDesktopComposeUiTest\n"
            "import io.github.takahirom.roborazzi.captureRoboImage\nimport org.junit.Test\n\n"
            "@OptIn(ExperimentalTestApi::class)\n"
            f"class RoborazziDesktopTest{c:02d} {{\n")
    for s in part:
        body += (f"    @Test fun f{s}() = runDesktopComposeUiTest({W}, {H}) {{\n"
                 f"        setContent {{ BenchTheme(benchTypography()) {{ Fixture{s}() }} }}\n"
                 f'        onRoot().captureRoboImage("build/goldens/f{s}.png")\n'
                 "    }\n")
    return body + "}\n"


def main(n):
    ids = [f"{i:03d}" for i in range(n)]
    for rel in TEST_DIRS.values():
        for f in (ROOT / rel).glob("*.kt"):  # top level only: hand-written support/ stays
            f.unlink()

    write("fixtures/src/bench/Fixtures.kt", fixtures(ids))
    write("viddik/src/test/kotlin/bench/ViddikFixtures.kt", viddik(ids))
    write("viddik-split/src/test/kotlin/bench/ViddikFixtures.kt", viddik(ids))
    for c, part in enumerate(chunks(ids)):
        write(f"{TEST_DIRS['paparazzi']}/PaparazziTest{c:02d}.kt", paparazzi(c, part))
        write(f"{TEST_DIRS['roborazzi-android']}/RoborazziAndroidTest{c:02d}.kt", roborazzi_android(c, part))
        write(f"{TEST_DIRS['roborazzi-desktop']}/RoborazziDesktopTest{c:02d}.kt", roborazzi_desktop(c, part))


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 10)
